"""Background-only cover contract. SVG text remains available for layout inference."""

COVER_BACKGROUND_RULES = """
【任务边界】
你只负责生成一张纯净的 16:9 PPT 封面背景，参考画布 1280×720。
标题和副标题将在背景生成后，由外部程序作为独立 SVG 图层叠加。
主题、标题、副标题只用于理解场景和氛围，不是需要绘制的文字；主题中的品牌名称也不要求生成品牌标识。
风格和颜色说明仅约束背景氛围和对比度；其中的主标题、副标题、标题颜色不能作为绘字指令。
生活方式或杂志 editorial 风格仅指摄影、配色与光影，不包含封面排字。

【SVG 使用规则——仅分析留白区域，禁止绘制内容】
本请求中的参考标题 SVG 是不可见的后期文字占位参考，不是要复现的图片或前景。
必须读取 id=title 和 id=subtitle 的完整 SVG，依据坐标、字号、行距、字距、文字长度及变换，判断各行与整个文字组的真实占用区域。
SVG 的文字内容仅用于判断长度和占位。绝不能把任何文字、字形或排版画进背景图片。
按整行文字和文字组的外接区域留白，并保留适当安全距离；不得沿字形轮廓留白，不得形成可辨认的文字形状。
文字安全区必须连续、平整、低信息量、低对比度，不放主体、装饰、明显纹理、强阴影或高反差边缘。
留白应自然延续背景底色，不显示边框、遮罩、卡片、占位线、文字框或任何标记。
主视觉根据 SVG 实际布局放在文字安全区相对一侧，不固定在左侧或右侧；主体边缘和阴影均不得侵入文字区域。

【背景绘制要求】
采用适合主题的光影、材质和克制构图。留白很大也不得主动填满。
所有场景物件均无文字、无标识：包装、容器、购物篮和餐具应为素面无品牌；不出现带字标签、价格牌、店招、菜单、海报、票据或屏幕界面。

【最终图片绝对禁止】
严禁任何汉字、字母、数字、标点、其他语言文字、乱码、仿文字笔画、手写字、书法、Logo、商标、水印、二维码、条形码。
严禁生成 SVG 中标题和副标题的原文、部分文字、翻译、缩写、变形字、模糊字或装饰化字形。
不能叠加 SVG 前景，也不能生成标题的阴影、描边、压印或文字形状的镂空。

【最终验收】
把后期 SVG 图层完全隐藏后，剩下的无字画面才是本次应输出的结果。
检查边角、物件表面和远处背景；任何文字、疑似文字和标识都要移除并恢复自然材质。
只输出等待后期叠加文字的纯净背景图片，不输出已经排好标题的完整封面。
""".strip()


def background_style(style: str) -> str:
    """Add drawing constraints without changing the commercial route or billing."""
    return f"{style}\n\n{COVER_BACKGROUND_RULES}"


def build_cover_background_prompt(topic: str, style: str, draft_svg: str) -> str:
    return (
        f"生成纯净的 16:9 PPT 封面背景。\n主题（仅理解场景，不绘制文字）：{topic}\n"
        f"视觉风格与配色（其中的标题信息只作上下文）：{style}\n\n"
        f"{COVER_BACKGROUND_RULES}\n\n"
        "【后期文字占位参考 SVG——只分析几何区域，禁止绘制内容】\n"
        f"{draft_svg}\n"
        "【占位参考结束】\n"
        "再次确认：上述 SVG 完全不出现在输出图片中，只保留它所需的连续留白。仅输出无字背景。"
    )

